/**
 * Hand-rolled, bounded-key catalogue — no ICU runtime, server-safe, and the
 * whole thing is one object per locale so a missing key is a type error rather
 * than an English string leaking into an Uzbek screen.
 *
 * English is the DEFAULT while the interface is being designed — it is the
 * language the work is reviewed in. UZ and RU are complete and switchable, and
 * the shipped default flips to "uz" before launch: the product is pitched as
 * the platform that speaks the language, so a judge or a merchant must land on
 * Uzbek, not English.
 *
 * UZ Cyrillic is deliberately not a locale — same call as the main app.
 */

export const LOCALES = ["en", "uz", "ru"] as const
export type Locale = (typeof LOCALES)[number]
export const DEFAULT_LOCALE: Locale = "en"

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value)
}

